"use client";

import Link from "next/link";
import { ArrowRight, CircleHelp, Lightbulb, Sparkles } from "lucide-react";
import { useMemo } from "react";
import { useRevenueData } from "@/components/data-provider";
import { RiskBadge } from "@/components/ui/status-badge";
import { ErrorState, LoadingState } from "@/components/ui/page-states";
import { isOpenStatus } from "@/lib/formatters";
import { formatCurrency, formatDate } from "@/lib/formatters";

export default function RecommendationsPage() {
  const { deals, loading, error, refresh } = useRevenueData();
  const recommendations = useMemo(() => deals
    .filter((deal) => isOpenStatus(deal.status) && Boolean(deal.recommended_action))
    .sort((a, b) => {
      const priority = { HIGH: 2, MEDIUM: 1, LOW: 0 };
      return priority[b.risk_level] - priority[a.risk_level] || b.risk_score - a.risk_score;
    }), [deals]);

  return (
    <>
      <div className="page-heading">
        <div><div className="eyebrow"><span className="eyebrow-dot" /> SALES ACTIONS</div><h1>Recommendations</h1><p>Evidence-based next steps, prioritized by deal risk.</p></div>
        <div className="recommendations-summary"><Sparkles size={15} /><strong>{recommendations.length}</strong> suggestions</div>
      </div>
      <div className="info-banner"><CircleHelp size={16} /><span>Recommendations are generated by the rule-based deal analysis. They are informational only; there is no action approval or execution endpoint.</span></div>
      {error && <ErrorState message={error} onRetry={() => void refresh()} />}
      {loading ? <LoadingState label="Loading recommendations" /> : recommendations.length === 0 ? (
        <div className="panel empty-state recommendations-empty"><div className="empty-icon"><Lightbulb size={19} /></div><strong>No recommendations to show</strong><span>Import CRM deals to generate next-step suggestions from available pipeline signals.</span><Link className="button button-primary" href="/import">Import CRM data</Link></div>
      ) : (
        <section className="recommendation-list" aria-label="Deal recommendations">
          {recommendations.map((deal, index) => (
            <article className="panel recommendation-card" key={deal.deal_id}>
              <div className="recommendation-card-rank">{String(index + 1).padStart(2, "0")}</div>
              <div className="recommendation-card-content">
                <div className="recommendation-card-top"><div><Link href={`/deals/${encodeURIComponent(deal.deal_id)}`} className="recommendation-account">{deal.account_name}<ArrowRight size={14} /></Link><span className="recommendation-deal-meta">{deal.deal_id} <i>·</i> {deal.stage} <i>·</i> {formatCurrency(deal.deal_value)}</span></div><RiskBadge level={deal.risk_level} /></div>
                <p className="recommendation-card-action">{deal.recommended_action}</p>
                <div className="recommendation-card-footer">
                  <span className="recommendation-evidence"><Lightbulb size={14} /><span>{deal.risk_reasons?.[0] || "Based on the current deal risk assessment."}</span></span>
                  <span className="recommendation-priority">Priority: <strong>{deal.risk_level === "HIGH" ? "Urgent" : deal.risk_level === "MEDIUM" ? "Upcoming" : "Monitor"}</strong></span>
                  <span className="recommendation-date">Close {formatDate(deal.expected_close_date)}</span>
                </div>
              </div>
            </article>
          ))}
        </section>
      )}
    </>
  );
}
